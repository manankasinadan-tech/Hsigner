package com.hephaistos.hsigner.engine

import com.hephaistos.hsigner.protocol.HephaistosContract

/**
 * Génère la documentation technique complète et téléchargeable (HSIGNER_README.md)
 * destinée aux utilisateurs, aux terminaux, aux développeurs d'applications tierces
 * et aux intelligences artificielles devant concevoir de futurs modules inter-opérables.
 */
object ReadmeDocumentGenerator {

    const val README_FILENAME = "HSIGNER_README.md"
    const val SPEC_FILENAME = "HSIGNER_API_SPEC.json"

    fun buildMarkdownReadme(rawManifestJson: String? = null): String = buildString {
        appendLine("# HSIGNER (`${HephaistosContract.MODULE_PACKAGE}`) — Guide d'Intégration Inter-Modulaire HEPHAISTOS")
        appendLine()
        appendLine("**HSIGNER** est un moteur Android 100 % headless (sans interface graphique) spécialisé dans l'inspection et la vérification cryptographique des signatures APK (**V1 JAR, V2, V3, V3.1 Key Rotation et V4 `.idsig`**).")
        appendLine("Il est conçu pour être commandé par **HEPHAISTOS** (`${HephaistosContract.LAUNCHER_PACKAGE}`), par tout futur **Terminal**, par d'autres **modules satellites** (`com.hephaistos.*`), ou par **toute application Android tierce**.")
        appendLine()
        appendLine("---")
        appendLine()
        appendLine("## 1. Découverte Automatique du Module")
        appendLine()
        appendLine("- **Package / Application ID** : `${HephaistosContract.MODULE_PACKAGE}`")
        appendLine("- **Service Moteur Exporté** : `${HephaistosContract.MODULE_PACKAGE}.ModuleEngineService`")
        appendLine("- **Intent-Filter** : `${HephaistosContract.ACTION_MODULE}` et `${HephaistosContract.ACTION_EXECUTE}`")
        appendLine("- **Meta-Data Manifeste** : `${HephaistosContract.META_DATA_MANIFEST}` (`@raw/hephaistos_manifest`)")
        appendLine("- **ContentProvider Synchrone** : `content://${HephaistosContract.CONTENT_PROVIDER_AUTHORITY}`")
        appendLine()
        appendLine("### Lecture dynamique du manuel machine-readable (`hephaistos_manifest.json`)")
        appendLine("Toute application ou IA peut interroger dynamiquement les capacités de HSIGNER via `PackageManager` :")
        appendLine("```kotlin")
        appendLine("val pm = context.packageManager")
        appendLine("val services = pm.queryIntentServices(Intent(\"${HephaistosContract.ACTION_MODULE}\"), PackageManager.GET_META_DATA)")
        appendLine("val hsignerInfo = services.firstOrNull { it.serviceInfo.packageName == \"${HephaistosContract.MODULE_PACKAGE}\" }")
        appendLine("val resId = hsignerInfo?.serviceInfo?.metaData?.getInt(\"${HephaistosContract.META_DATA_MANIFEST}\") ?: 0")
        appendLine("val manifestJson = pm.getResourcesForApplication(\"${HephaistosContract.MODULE_PACKAGE}\").openRawResource(resId).bufferedReader().readText()")
        appendLine("```")
        appendLine()
        appendLine("---")
        appendLine()
        appendLine("## 2. Protocole de Commande (`${HephaistosContract.ACTION_EXECUTE}`)")
        appendLine()
        appendLine("### Extras obligatoires et optionnelles envoyées au Service")
        appendLine("| Extra | Type | Obligatoire | Description |")
        appendLine("|---|---|---|---|")
        appendLine("| `${HephaistosContract.EXTRA_COMMAND_ID}` | `String` | Oui | `verify_apk`, `get_readme`, `export_readme_file`, `inspect_capabilities` |")
        appendLine("| `${HephaistosContract.EXTRA_PARAMS_JSON}` | `String` (JSON) | Selon commande | Paramètres JSON de la commande |")
        appendLine("| `${HephaistosContract.EXTRA_SOURCE_PACKAGE}` | `String` | Recommandé | Package de l'application appelante recevant `COMMAND_RESULT` |")
        appendLine("| `${HephaistosContract.EXTRA_TASK_ID}` | `String` | Optionnel | Identifiant de corrélation pour suivi `PROGRESS` et annulation `CANCEL_TASK` |")
        appendLine()
        appendLine("### Exemple Kotlin complet pour commander HSIGNER depuis une app ou un module")
        appendLine("```kotlin")
        appendLine("val params = org.json.JSONObject().apply {")
        appendLine("    put(\"apk_uris\", org.json.JSONArray(listOf(apkContentUri.toString())))")
        appendLine("    put(\"include_raw_bits\", true)")
        appendLine("    put(\"include_json\", true)")
        appendLine("}")
        appendLine("val intent = Intent(\"${HephaistosContract.ACTION_EXECUTE}\").apply {")
        appendLine("    setClassName(\"${HephaistosContract.MODULE_PACKAGE}\", \"${HephaistosContract.MODULE_PACKAGE}.ModuleEngineService\")")
        appendLine("    putExtra(\"${HephaistosContract.EXTRA_COMMAND_ID}\", \"${HephaistosContract.CMD_VERIFY_APK}\")")
        appendLine("    putExtra(\"${HephaistosContract.EXTRA_PARAMS_JSON}\", params.toString())")
        appendLine("    putExtra(\"${HephaistosContract.EXTRA_SOURCE_PACKAGE}\", context.packageName)")
        appendLine("    addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)")
        appendLine("}")
        appendLine("if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) context.startForegroundService(intent) else context.startService(intent)")
        appendLine("```")
        appendLine()
        appendLine("### Exemple de commande depuis un Terminal Android / ADB")
        appendLine("```bash")
        appendLine("# Vérifier un ou plusieurs APK")
        appendLine("am start-foreground-service -n ${HephaistosContract.MODULE_PACKAGE}/.ModuleEngineService \\")
        appendLine("  -a ${HephaistosContract.ACTION_EXECUTE} \\")
        appendLine("  --es ${HephaistosContract.EXTRA_COMMAND_ID} ${HephaistosContract.CMD_VERIFY_APK} \\")
        appendLine("  --es ${HephaistosContract.EXTRA_SOURCE_PACKAGE} ${HephaistosContract.LAUNCHER_PACKAGE} \\")
        appendLine("  --es ${HephaistosContract.EXTRA_PARAMS_JSON} '{\"apk_uris\":[\"/storage/emulated/0/Download/app.apk\"]}'")
        appendLine()
        appendLine("# Annuler une tâche en cours")
        appendLine("am broadcast -a ${HephaistosContract.ACTION_CANCEL_TASK} -p ${HephaistosContract.MODULE_PACKAGE} --es ${HephaistosContract.EXTRA_TASK_ID} \"<TASK_ID>\"")
        appendLine("```")
        appendLine()
        appendLine("---")
        appendLine()
        appendLine("## 3. Réception des Logs, Progressions et Résultats")
        appendLine()
        appendLine("HSIGNER émet des broadcasts explicites vers `${HephaistosContract.LAUNCHER_PACKAGE}` ET vers votre `SOURCE_PACKAGE` :")
        appendLine("1. **`${HephaistosContract.ACTION_LOG}`** : `SOURCE_PACKAGE`, `LEVEL` (`INFO` | `OUT` | `ERR`), `MESSAGE` (rapport terminal ligne par ligne / bloc par bloc).")
        appendLine("2. **`${HephaistosContract.ACTION_PROGRESS}`** : `SOURCE_PACKAGE`, `TASK_ID`, `TITLE`, `MESSAGE`, `PROGRESS` (`0..100` ou `-1`), `COMPLETED` (`Boolean`), `ERROR`, `CAN_CANCEL`.")
        appendLine("3. **`${HephaistosContract.ACTION_COMMAND_RESULT}`** : `COMMAND_ID`, `SOURCE_PACKAGE`, `RESULT_JSON` (objet JSON structuré complet), `ERROR`.")
        appendLine()
        appendLine("```kotlin")
        appendLine("// BroadcastReceiver dans votre application appelante")
        appendLine("val filter = IntentFilter().apply {")
        appendLine("    addAction(\"${HephaistosContract.ACTION_COMMAND_RESULT}\")")
        appendLine("    addAction(\"${HephaistosContract.ACTION_LOG}\")")
        appendLine("    addAction(\"${HephaistosContract.ACTION_PROGRESS}\")")
        appendLine("}")
        appendLine("```")
        appendLine()
        appendLine("---")
        appendLine()
        appendLine("## 4. API Synchrone via `ContentProvider` (Sans Broadcast)")
        appendLine()
        appendLine("Pour un terminal synchrone ou une intégration simplifiée, interrogez `content://${HephaistosContract.CONTENT_PROVIDER_AUTHORITY}` :")
        appendLine("- **Télécharger ce README** : `contentResolver.openInputStream(Uri.parse(\"content://${HephaistosContract.CONTENT_PROVIDER_AUTHORITY}/readme\"))`")
        appendLine("- **Lire la spec JSON brute** : `contentResolver.openInputStream(Uri.parse(\"content://${HephaistosContract.CONTENT_PROVIDER_AUTHORITY}/manifest\"))`")
        appendLine("- **Appeler `verify_apk` en synchrone** :")
        appendLine("```kotlin")
        appendLine("val args = Bundle().apply {")
        appendLine("    putString(\"${HephaistosContract.EXTRA_PARAMS_JSON}\", \"{\\\"apk_uris\\\":[\\\"/data/local/tmp/app.apk\\\"]}\")")
        appendLine("}")
        appendLine("val res = contentResolver.call(Uri.parse(\"content://${HephaistosContract.CONTENT_PROVIDER_AUTHORITY}\"), \"${HephaistosContract.CMD_VERIFY_APK}\", null, args)")
        appendLine("val resultJson = res?.getString(\"${HephaistosContract.EXTRA_RESULT_JSON}\")")
        appendLine("```")
        appendLine()
        appendLine("---")
        appendLine()
        appendLine("## 5. Référence des Commandes & Schéma `RESULT_JSON`")
        appendLine()
        appendLine("### Commande `verify_apk`")
        appendLine("- **Paramètres** : `apk_uris` (Array/String, requis), `idsig_uris` (Array, optionnel pour V4), `include_raw_bits` (Boolean, défaut `true`), `include_json` (Boolean, défaut `true`).")
        appendLine("- **Champs retournés par APK dans `results[]`** :")
        appendLine("  - `app_name`, `package_name`, `version_name`, `version_code`, `min_sdk_version`, `target_sdk_version`, `path`, `file_size_bytes`")
        appendLine("  - `verified` (Boolean), `scheme_summary` (ex: `\"V1 + V2 + V3\"`), `detected_schemes`, `verified_schemes`, `schemes[]` (détails par V1/V2/V3/V3.1/V4)")
        appendLine("  - `v3_lineage[]`, `source_stamp_present`, `source_stamp_verified`")
        appendLine("  - `certificates[]` : `index`, `type`, `version`, `serial_number_decimal`, `serial_number_hex`, `subject_dn`, `issuer_dn`, `self_signed`, `valid_from`, `valid_to`, `signature_algorithm`, `hash_code_hex`, `hash_code_int`, `crc32_hex`, `crc32_decimal`, `md5`, `sha1`, `sha224`, `sha256`, `sha384`, `sha512`, `certificate_base64`, `signature_bits_hex`, `public_key`, `signature_base64`, `raw_pkcs7_or_v4_signature_base64`, `source_schemes`")
        appendLine("  - `terminal_report` : Rapport texte complet prêt à afficher dans un terminal.")
        appendLine()
        appendLine("### Consignes pour les IA générant de futurs modules HEPHAISTOS")
        appendLine("1. Découvrez toujours `${HephaistosContract.MODULE_PACKAGE}` via `${HephaistosContract.ACTION_MODULE}` + `<queries>` dans votre manifeste.")
        appendLine("2. Passez des URIs `content://` avec `FLAG_GRANT_READ_URI_PERMISSION` (ou des chemins lisibles) dans `apk_uris` — n'utilisez jamais `READ_EXTERNAL_STORAGE`.")
        appendLine("3. Passez systématiquement votre `context.packageName` dans `${HephaistosContract.EXTRA_SOURCE_PACKAGE}` pour recevoir `COMMAND_RESULT` et les logs en miroir.")
        appendLine("4. Gérez `TransactionTooLargeException` sur Android : si `RESULT_JSON` contient `export_report_uri`, vous pouvez aussi lire le rapport complet via `contentResolver.openInputStream(Uri.parse(uri))`.")
        if (!rawManifestJson.isNullOrBlank()) {
            appendLine()
            appendLine("---")
            appendLine()
            appendLine("## 6. Manifeste Complet Embarqué (`hephaistos_manifest.json`)")
            appendLine("```json")
            appendLine(rawManifestJson.trim())
            appendLine("```")
        }
    }
}
